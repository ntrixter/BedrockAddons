#!/usr/bin/env python3
"""Generate every recipe in stonecutter-decompression/behavior_pack/recipes/,
and the test-kit function that hands out one of each input block.

    python3 stonecutter-decompression/tools/gen_recipes.py           # write
    python3 stonecutter-decompression/tools/gen_recipes.py --check   # verify, write nothing
    python3 stonecutter-decompression/tools/gen_recipes.py --check --vanilla <bedrock-samples>

The table below is the source of truth; the files are its output. Change the
table, rerun, commit the diff.

THE RULE
  A block returns exactly what it cost to craft: the vanilla recipe's
  ingredient count divided by its output count.

  One exception is allowed per row: an extra ingredient that is used up and
  not returned. Dark prismarine is 8 shards plus a black dye; it gives back
  the 8 shards and the dye is lost. NOT_RETURNED names those extras, so the
  vanilla check still knows exactly which recipe it is comparing against.

--vanilla points at a checkout of Mojang's bedrock-samples. With it, --check
also confirms every id exists in metadata/vanilladata_modules/mojang-items.json
and that every count matches the shipped crafting recipe in
behavior_pack/recipes/. That needs the checkout, so CI does not run it; run it
by hand whenever the table changes.

Deliberately absent: nether_wart_block, amethyst_block and dripstone_block, which spawn naturally in bulk and would become farms for
their items; magma, for the same reason with magma cream; and resin_block,
which vanilla already uncrafts in a crafting grid.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ADDON = Path(__file__).resolve().parent.parent
RECIPES = ADDON / "behavior_pack" / "recipes"
TEST_KIT = ADDON / "behavior_pack" / "functions" / "stonecutter_decompression" / "test_kit.mcfunction"

PREFIX = "uncraft"
FORMAT_VERSION = "1.20.10"

# (input block, result item, count). Ids without the minecraft: namespace.
TABLE = [
    ("bamboo_block", "bamboo", 9),
    ("prismarine_bricks", "prismarine_shard", 9),
    ("prismarine", "prismarine_shard", 4),
    ("dark_prismarine", "prismarine_shard", 8),
    ("honeycomb_block", "honeycomb", 4),
    ("quartz_block", "quartz", 4),
    ("sandstone", "sand", 4),
    ("red_sandstone", "red_sand", 4),
    ("white_wool", "string", 4),
    ("brick_block", "brick", 4),
    ("nether_brick", "netherbrick", 4),
    ("resin_bricks", "resin_brick", 4),
    ("glowstone", "glowstone_dust", 4),
    ("melon_block", "melon_slice", 9),
    ("clay", "clay_ball", 4),
    ("snow", "snowball", 4),
    ("packed_ice", "ice", 9),
    ("blue_ice", "packed_ice", 9),
]

# Input block -> ingredients its vanilla recipe uses up that are not returned.
NOT_RETURNED = {
    "dark_prismarine": {"black_dye"},
}

# The test kit hands out the station too. Its item id is not "stonecutter": that
# id does not exist, and one bad line makes Bedrock discard the whole function.
STATION = "stonecutter_block"

# Older ids vanilla's own recipes still use for the same item.
ALIASES = {
    "minecraft:chorus_fruit_popped": "minecraft:popped_chorus_fruit",
    "minecraft:melon": "minecraft:melon_slice",
}


def recipe(block: str, item: str, count: int) -> dict:
    return {
        "format_version": FORMAT_VERSION,
        "minecraft:recipe_shapeless": {
            "description": {"identifier": f"{PREFIX}:{block}_to_{item}"},
            "tags": ["stonecutter"],
            "ingredients": [{"item": f"minecraft:{block}"}],
            "unlock": [{"item": f"minecraft:{block}"}],
            "result": {"item": f"minecraft:{item}", "count": count},
        },
    }


def render(data: dict) -> str:
    return json.dumps(data, indent=2) + "\n"


def expected_files() -> dict[Path, str]:
    files = {RECIPES / f"{b}_to_{i}.json": render(recipe(b, i, c)) for b, i, c in TABLE}
    lines = [
        "# Test kit: a stonecutter and one of every block this pack decompresses.",
        "# Run with /function stonecutter_decompression/test_kit (cheats on).",
        "# Generated by tools/gen_recipes.py; edit the table there, not this file.",
        f"give @s {STATION} 1",
    ] + [f"give @s {b} 1" for b, _, _ in TABLE]
    files[TEST_KIT] = "\n".join(lines) + "\n"
    return files


def strip_comments(text: str) -> str:
    # Vanilla JSON carries // comments; keep line numbers, drop the comment.
    return "\n".join(line.split("//")[0] for line in text.splitlines())


def ingredient_name(entry) -> str:
    """An item id, or "tag:<name>" for an ingredient matched by item tag."""
    if not isinstance(entry, dict):
        return entry
    return entry.get("item") or f"tag:{entry.get('tag', '')}"


def vanilla_costs(recipes_dir: Path) -> dict[str, list[tuple[str, dict, int]]]:
    """Map output item -> [(file, {ingredient: count}, output count)]."""
    out: dict[str, list] = {}
    for path in sorted(recipes_dir.glob("*.json")):
        try:
            doc = json.loads(strip_comments(path.read_text(encoding="utf-8")))
        except ValueError:
            continue
        for kind, body in doc.items():
            if not kind.startswith("minecraft:recipe_") or not isinstance(body, dict):
                continue
            if "crafting_table" not in body.get("tags", []):
                continue
            result = body.get("result")
            result = result[0] if isinstance(result, list) else result
            if not isinstance(result, dict):
                continue
            cost: dict[str, int] = {}
            if kind == "minecraft:recipe_shaped":
                key = body["key"]
                for row in body["pattern"]:
                    for ch in row:
                        if ch != " ":
                            name = ingredient_name(key[ch])
                            cost[name] = cost.get(name, 0) + 1
            else:
                for ing in body.get("ingredients", []):
                    name = ingredient_name(ing)
                    n = ing.get("count", 1) if isinstance(ing, dict) else 1
                    cost[name] = cost.get(name, 0) + n
            cost = {ALIASES.get(k, k): v for k, v in cost.items()}
            out.setdefault(result.get("item"), []).append((path.name, cost, result.get("count", 1)))
    return out


def check_vanilla(root: Path) -> list[str]:
    problems = []
    items_doc = json.loads((root / "metadata/vanilladata_modules/mojang-items.json").read_text())
    items = {i["name"] for i in items_doc["data_items"]}
    costs = vanilla_costs(root / "behavior_pack/recipes")
    if f"minecraft:{STATION}" not in items:
        problems.append(f"minecraft:{STATION} (test kit station) is not in mojang-items.json")
    for block, item, count in TABLE:
        for name in (block, item):
            if f"minecraft:{name}" not in items:
                problems.append(f"minecraft:{name} is not in mojang-items.json")
        lost = {f"minecraft:{x}" for x in NOT_RETURNED.get(block, ())}
        matches = [
            (f, c, n) for f, c, n in costs.get(f"minecraft:{block}", [])
            if set(c) == {f"minecraft:{item}"} | lost
        ]
        if not matches:
            extra = f" plus {', '.join(sorted(lost))}" if lost else " alone"
            problems.append(f"no vanilla recipe crafts {block} from {item}{extra}")
            continue
        f, c, n = matches[0]
        used = c[f"minecraft:{item}"]
        if used % n:
            problems.append(f"{block}: {f} uses {used} {item} for {n}, not a whole number each")
        elif used // n != count:
            problems.append(f"{block}: table says {count} {item}, {f} says {used // n}")
    return problems


def main(argv: list[str]) -> int:
    check = "--check" in argv
    vanilla = None
    if "--vanilla" in argv:
        vanilla = Path(argv[argv.index("--vanilla") + 1])

    blocks = [b for b, _, _ in TABLE]
    if len(set(blocks)) != len(blocks):
        print("duplicate input block in TABLE", file=sys.stderr)
        return 1

    files = expected_files()
    problems = []
    if check:
        for path, text in files.items():
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                problems.append(f"{path.relative_to(ADDON)} is missing or out of date")
        wanted = set(files)
        for path in RECIPES.glob("*.json"):
            if path not in wanted:
                problems.append(f"{path.relative_to(ADDON)} is not in the table")
        if vanilla:
            problems += check_vanilla(vanilla)
        for p in problems:
            print(p, file=sys.stderr)
        print(f"{len(TABLE)} recipes: {'clean' if not problems else f'{len(problems)} problem(s)'}")
        return 1 if problems else 0

    RECIPES.mkdir(parents=True, exist_ok=True)
    TEST_KIT.parent.mkdir(parents=True, exist_ok=True)
    for path in RECIPES.glob("*.json"):
        if path not in files:
            path.unlink()
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(TABLE)} recipes and the test kit")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
